let selectedDateVal = "Lun 12 Mag";
let selectedSlotVal = "Mattina (09:00 - 13:30)";

function initBookingWizard() {
  const bookingForm = document.getElementById('booking-flow');
  if (!bookingForm) return;

  window.selectDate = function (btn) {
    document.querySelectorAll('.day-slot').forEach(function (el) {
      el.className = 'day-slot p-2.5 rounded-xl bg-[#1a1916] text-[#f5efe6] text-center shadow-sm flex flex-col items-center justify-center hover:border-[#d4af37] border border-[#d4af37]/25 transition-all';
      const spans = el.querySelectorAll('span');
      if (spans[0]) spans[0].className = 'font-label-caps text-[10px] uppercase text-[#a89f91]';
      if (spans[1]) spans[1].className = 'font-title-editorial text-lg text-[#f5efe6]';
      if (spans[2]) spans[2].className = 'font-label-caps text-[9px] text-[#d4af37]';
    });

    btn.className = 'day-slot p-2.5 rounded-xl bg-[#d4af37] text-[#0f0e0c] text-center shadow-[0_0_15px_rgba(212,175,55,0.25)] flex flex-col items-center justify-center transition-all border border-[#d4af37]';
    const spans = btn.querySelectorAll('span');
    if (spans[0]) spans[0].className = 'font-label-caps text-[10px] uppercase font-bold text-[#0f0e0c]';
    if (spans[1]) spans[1].className = 'font-title-editorial text-lg font-semibold text-[#0f0e0c]';
    if (spans[2]) spans[2].className = 'font-label-caps text-[9px] text-[#0f0e0c] font-bold';

    selectedDateVal = btn.getAttribute('data-date') || "Giorno Selezionato";
    updateSummary();
  };

  window.selectSlot = function (btn) {
    document.querySelectorAll('.time-slot').forEach(function (el) {
      el.classList.remove('border-[#d4af37]', 'shadow-[0_0_15px_rgba(212,175,55,0.15)]');
      el.classList.add('border-[#d4af37]/25');
      const radio = el.querySelector('.time-radio');
      if (radio) {
        radio.textContent = 'radio_button_unchecked';
        radio.classList.remove('text-[#d4af37]');
        radio.classList.add('text-[#a89f91]');
      }
    });

    btn.classList.remove('border-[#d4af37]/25');
    btn.classList.add('border-[#d4af37]', 'shadow-[0_0_15px_rgba(212,175,55,0.15)]');
    const activeRadio = btn.querySelector('.time-radio');
    if (activeRadio) {
      activeRadio.textContent = 'check_circle';
      activeRadio.classList.remove('text-[#a89f91]');
      activeRadio.classList.add('text-[#d4af37]');
    }

    selectedSlotVal = btn.getAttribute('data-slot') || "Orario concordato";
    updateSummary();
  };

  window.updateSummary = function () {
    const checkedTreatment = document.querySelector('input[name="treatment"]:checked');
    if (!checkedTreatment) return;

    const treatmentTitle = checkedTreatment.value;
    const price = checkedTreatment.getAttribute('data-price') || "60";
    const duration = checkedTreatment.getAttribute('data-duration') || "60 min";

    document.querySelectorAll('.ritual-card').forEach(function (card) {
      const radio = card.querySelector('input[type="radio"]');
      const indicator = card.querySelector('.check-indicator');
      if (radio && radio.checked) {
        card.classList.add('border-[#d4af37]', 'shadow-[0_0_15px_rgba(212,175,55,0.15)]');
        card.classList.remove('border-[#d4af37]/25');
        if (indicator) {
          indicator.textContent = 'radio_button_checked';
          indicator.classList.add('text-[#d4af37]');
          indicator.classList.remove('text-[#a89f91]');
        }
      } else {
        card.classList.remove('border-[#d4af37]', 'shadow-[0_0_15px_rgba(212,175,55,0.15)]');
        card.classList.add('border-[#d4af37]/25');
        if (indicator) {
          indicator.textContent = 'radio_button_unchecked';
          indicator.classList.remove('text-[#d4af37]');
          indicator.classList.add('text-[#a89f91]');
        }
      }
    });

    const summaryTreatment = document.getElementById('summary-treatment');
    const summaryDuration = document.getElementById('summary-duration');
    const summaryDate = document.getElementById('summary-date');
    const summaryTime = document.getElementById('summary-time');
    const summaryTotal = document.getElementById('summary-total');

    if (summaryTreatment) summaryTreatment.textContent = treatmentTitle;
    if (summaryDuration) summaryDuration.textContent = duration;
    if (summaryDate) summaryDate.textContent = selectedDateVal;
    if (summaryTime) summaryTime.textContent = selectedSlotVal;
    if (summaryTotal) summaryTotal.textContent = price + '€';
  };

  window.submitBooking = function () {
    const checkedTreatment = document.querySelector('input[name="treatment"]:checked');
    const treatmentTitle = checkedTreatment ? checkedTreatment.value : 'Rituale Olistico';
    const nameInput = document.getElementById('client-name');
    const name = nameInput ? nameInput.value : 'Ospite';

    const modal = document.getElementById('confirmation-modal');
    if (modal) {
      const mName = document.getElementById('modal-client-name');
      const mTreatment = document.getElementById('modal-treatment');
      const mDateTime = document.getElementById('modal-datetime');

      if (mName) mName.textContent = name || 'Ospite';
      if (mTreatment) mTreatment.textContent = treatmentTitle;
      if (mDateTime) mDateTime.textContent = selectedDateVal + ' • ' + selectedSlotVal;

      modal.classList.remove('hidden');
      modal.classList.add('flex');
    }
  };

  window.closeConfirmationModal = function () {
    const modal = document.getElementById('confirmation-modal');
    if (modal) {
      modal.classList.add('hidden');
      modal.classList.remove('flex');
    }
  };

  updateSummary();
}

