window.inviaWhatsApp = function (whatsappNumber) {
  const number = whatsappNumber || (window.rdlThemeData && window.rdlThemeData.whatsapp) || '393334918428';
  const cleanNumber = number.replace(/\D/g, '');

  const nomeInput = document.getElementById('input-nome');
  const telInput = document.getElementById('input-tel');
  const trattInput = document.getElementById('input-trattamento');
  const dataInput = document.getElementById('input-data');

  const nome = nomeInput ? (nomeInput.value || 'Ospite') : 'Ospite';
  const tel = telInput ? (telInput.value || '') : '';
  const trattamento = trattInput ? (trattInput.value || 'Trattamento Olistico') : 'Trattamento Olistico';
  const data = dataInput ? (dataInput.value || 'Da concordare') : 'Da concordare';

  const currentLang = localStorage.getItem('rdl_lang') || 'it';
  let testo = '';

  if (currentLang === 'es') {
    testo = `Estimada Elena, deseo solicitar una cita en Radici di Luna:\n\n` +
            `• Nombre: ${nome}\n` +
            `• Teléfono: ${tel}\n` +
            `• Tratamiento: ${trattamento}\n` +
            `• Fecha/Hora preferida: ${data}\n\n` +
            `Quedo a la espera de confirmación. ¡Muchas gracias!`;
  } else if (currentLang === 'en') {
    testo = `Dear Elena, I would like to request an appointment at Radici di Luna:\n\n` +
            `• Name: ${nome}\n` +
            `• Phone: ${tel}\n` +
            `• Treatment: ${trattamento}\n` +
            `• Preferred Day/Time: ${data}\n\n` +
            `Looking forward to your confirmation. Thank you!`;
  } else {
    testo = `Gentile Elena, vorrei richiedere un appuntamento presso Radici di Luna:\n\n` +
            `• Nome: ${nome}\n` +
            `• Telefono: ${tel}\n` +
            `• Trattamento: ${trattamento}\n` +
            `• Preferenza data/ora: ${data}\n\n` +
            `Resto a disposizione per conferma. Grazie!`;
  }

  const url = `https://wa.me/${cleanNumber}?text=${encodeURIComponent(testo)}`;
  window.open(url, '_blank');
};

/* ----------------------------------------------------
 * 6. Smooth Scroll Helper
 * ---------------------------------------------------- */
function initSmoothScroll() {
  document.querySelectorAll('a[href^="#"]').forEach(function (anchor) {
    anchor.addEventListener('click', function (e) {
      const targetId = this.getAttribute('href');
      if (targetId === '#' || targetId === '' || targetId.startsWith('#modal-')) return;

      const targetEl = document.querySelector(targetId);
      if (targetEl) {
        e.preventDefault();
        targetEl.scrollIntoView({
          behavior: 'smooth',
          block: 'start'
        });
      }
    });
  });
}

/* ----------------------------------------------------
 * 7. Cookie Consent & Technical Blocking (GDPR Compliant)
 * ---------------------------------------------------- */
const RDL_COOKIE_KEY = 'rdl_cookie_consent_v1';

window.rdlGetConsent = function () {
  try {
    const raw = localStorage.getItem(RDL_COOKIE_KEY);
    return raw ? JSON.parse(raw) : null;
  } catch (e) {
    return null;
  }
};

window.rdlHasConsent = function (category) {
  if (category === 'necessary') return true;
  const consent = window.rdlGetConsent();
  if (!consent) return false;
  return Boolean(consent[category]);
};

window.rdlSetConsent = function (consentObj) {
  try {
    localStorage.setItem(RDL_COOKIE_KEY, JSON.stringify(consentObj));
  } catch (e) {}

  // Dispatch global event for external scripts / tag managers
  try {
    window.dispatchEvent(new CustomEvent('rdl:consentUpdated', { detail: consentObj }));
  } catch (e) {}

  // Hide banner with smooth slide-down animation
  const banner = document.getElementById('rdl-cookie-banner');
  if (banner) {
    banner.classList.remove('cb-visible');
    banner.classList.add('cb-hidden');
    setTimeout(function () {
      banner.classList.add('hidden');
    }, 450);
  }
  window.rdlCloseCookiePreferences();
};

window.rdlAcceptAllCookies = function () {
  const consent = {
    necessary: true,
    analytics: true,
    marketing: true,
    timestamp: Date.now()
  };
  window.rdlSetConsent(consent);
};

window.rdlRejectCookies = function () {
  const consent = {
    necessary: true,
    analytics: false,
    marketing: false,
    timestamp: Date.now()
  };
  window.rdlSetConsent(consent);
};

window.rdlOpenCookiePreferences = function () {
  const modal = document.getElementById('rdl-cookie-preferences-modal');
  if (!modal) return;

  const currentConsent = window.rdlGetConsent() || { analytics: false, marketing: false };
  const analyticsInput = document.getElementById('rdl-toggle-analytics');
  const marketingInput = document.getElementById('rdl-toggle-marketing');

  if (analyticsInput) analyticsInput.checked = Boolean(currentConsent.analytics);
  if (marketingInput) marketingInput.checked = Boolean(currentConsent.marketing);

  modal.classList.remove('hidden');
  modal.classList.add('flex');
  document.body.style.overflow = 'hidden';
};

window.rdlCloseCookiePreferences = function () {
  const modal = document.getElementById('rdl-cookie-preferences-modal');
  if (modal) {
    modal.classList.add('hidden');
    modal.classList.remove('flex');
    document.body.style.overflow = '';
  }
};

window.rdlSaveCookiePreferences = function () {
  const analyticsInput = document.getElementById('rdl-toggle-analytics');
  const marketingInput = document.getElementById('rdl-toggle-marketing');

  const consent = {
    necessary: true,
    analytics: analyticsInput ? analyticsInput.checked : false,
    marketing: marketingInput ? marketingInput.checked : false,
    timestamp: Date.now()
  };
  window.rdlSetConsent(consent);
};

function initCookieConsent() {
  const banner = document.getElementById('rdl-cookie-banner');
  if (!banner) return;

  const consent = window.rdlGetConsent();
  if (!consent) {
    // Show banner after brief delay for smooth entrance
    setTimeout(function () {
      banner.classList.remove('hidden');
      void banner.offsetWidth; // force reflow
      banner.classList.remove('cb-hidden');
      banner.classList.add('cb-visible');
    }, 600);
  } else {
    banner.classList.add('hidden');
    banner.classList.add('cb-hidden');
  }

  // Close preferences modal on backdrop click
  const prefModal = document.getElementById('rdl-cookie-preferences-modal');
  if (prefModal) {
    prefModal.addEventListener('click', function (e) {
      if (e.target === prefModal) window.rdlCloseCookiePreferences();
    });
  }
}

/* ----------------------------------------------------
 * 8. Legal Documents Modal (Privacy, Cookies, Terms, Disclaimer)
 * ---------------------------------------------------- */
window.rdlOpenLegalModal = function (tab) {
  const modal = document.getElementById('rdl-legal-modal');
  if (!modal) return;

  modal.classList.remove('hidden');
  modal.classList.add('flex');
  document.body.style.overflow = 'hidden';

  window.rdlSwitchLegalTab(tab || 'privacy');
};

window.rdlCloseLegalModal = function () {
  const modal = document.getElementById('rdl-legal-modal');
  if (modal) {
    modal.classList.add('hidden');
    modal.classList.remove('flex');
    document.body.style.overflow = '';
  }
};

window.rdlSwitchLegalTab = function (activeTab) {
  const tabs = ['privacy', 'cookies', 'terms', 'disclaimer'];
  tabs.forEach(function (tab) {
    const panel = document.getElementById('rdl-legal-content-' + tab);
    const btn = document.getElementById('rdl-legal-tab-btn-' + tab);
    if (panel) {
      if (tab === activeTab) {
        panel.classList.remove('hidden');
      } else {
        panel.classList.add('hidden');
      }
    }
    if (btn) {
      if (tab === activeTab) {
        btn.classList.add('border-[#d4af37]', 'text-[#d4af37]', 'bg-[#1a1916]');
        btn.classList.remove('border-transparent', 'text-[#a89f91]');
      } else {
        btn.classList.remove('border-[#d4af37]', 'text-[#d4af37]', 'bg-[#1a1916]');
        btn.classList.add('border-transparent', 'text-[#a89f91]');
      }
    }
  });

  const contentArea = document.getElementById('rdl-legal-scroll-area');
  if (contentArea) contentArea.scrollTop = 0;
};

function initLegalModals() {
  document.querySelectorAll('.rdl-legal-trigger').forEach(function (link) {
    link.addEventListener('click', function (e) {
      const href = this.getAttribute('href') || '';
      const tab = this.getAttribute('data-tab') || 'privacy';

      // If it's a modal hash or empty, intercept and open the modal
      if (href.startsWith('#') || href === '') {
        e.preventDefault();
        window.rdlOpenLegalModal(tab);
      }
    });
  });

  const legalModal = document.getElementById('rdl-legal-modal');
  if (legalModal) {
    legalModal.addEventListener('click', function (e) {
      if (e.target === legalModal) window.rdlCloseLegalModal();
    });
  }

  // Handle ESC key for all modals
  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape') {
      window.rdlCloseLegalModal();
      window.rdlCloseCookiePreferences();
    }
  });
}
