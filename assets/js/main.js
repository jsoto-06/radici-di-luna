window.setLanguage = function (targetLang) {
  const lang = (targetLang || 'it').toLowerCase();
  localStorage.setItem('rdl_lang', lang);

  // 1. Update active states on Desktop Header Pill
  document.querySelectorAll('#header-lang-picker .lang-switch-btn').forEach(function (btn) {
    const btnLang = btn.getAttribute('data-lang');
    const isFirst = btnLang === 'it';
    const isLast = btnLang === 'es';
    const padClass = isFirst ? 'pr-2' : (isLast ? 'pl-2' : 'px-2');
    if (btnLang === lang) {
      btn.className = 'lang-switch-btn ' + padClass + ' font-bold text-[#d4af37] cursor-pointer transition-colors';
    } else {
      btn.className = 'lang-switch-btn ' + padClass + ' text-[#a89f91] hover:text-[#f5efe6] cursor-pointer transition-colors';
    }
  });

  // 2. Update active states on Mobile Drawer Switcher
  document.querySelectorAll('#drawer-lang-picker .mobile-lang-btn').forEach(function (btn) {
    const btnLang = btn.getAttribute('data-lang');
    if (btnLang === lang) {
      btn.className = 'mobile-lang-btn font-bold text-[#d4af37] cursor-pointer transition-colors';
    } else {
      btn.className = 'mobile-lang-btn text-[#a89f91] hover:text-[#f5efe6] cursor-pointer transition-colors';
    }
  });

  // 3. Update Manifesto Tabs if present on Chi Sono page
  document.querySelectorAll('.lang-tab').forEach(function (tab) {
    const tabId = tab.id;
    if (tabId === 'tab-' + lang) {
      tab.className = 'lang-tab px-4 py-2 rounded-full font-label-caps text-xs uppercase transition-all duration-200 bg-[#d4af37] text-[#0f0e0c] font-semibold shadow-sm';
    } else {
      tab.className = 'lang-tab px-4 py-2 rounded-full font-label-caps text-xs uppercase text-[#a89f91] hover:text-[#f5efe6] transition-all duration-200';
    }
  });

  // 4. Update Manifesto Contents if present on Chi Sono page
  const contents = document.querySelectorAll('.lang-content');
  if (contents.length) {
    contents.forEach(function (content) {
      content.classList.add('hidden', 'opacity-0');
      content.classList.remove('opacity-100');
    });

    const activeContent = document.getElementById('content-' + lang);
    if (activeContent) {
      activeContent.classList.remove('hidden');
      setTimeout(function () {
        activeContent.classList.remove('opacity-0');
        activeContent.classList.add('opacity-100');
      }, 20);
    }
  }

  // 5. Translate all DOM elements with [data-i18n]
  const dict = rdlDictionary[lang] || rdlDictionary['it'];
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    if (!el.hasAttribute('data-i18n-original')) {
      el.setAttribute('data-i18n-original', el.textContent.trim());
    }
    const key = el.getAttribute('data-i18n');
    if (lang === 'it') {
      const orig = el.getAttribute('data-i18n-original');
      el.textContent = orig || (dict[key] || '');
    } else if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // 6. Translate all input placeholders with [data-i18n-placeholder]
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
    if (!el.hasAttribute('data-placeholder-original')) {
      el.setAttribute('data-placeholder-original', el.getAttribute('placeholder') || '');
    }
    const key = el.getAttribute('data-i18n-placeholder');
    if (lang === 'it') {
      const orig = el.getAttribute('data-placeholder-original');
      el.setAttribute('placeholder', orig || (dict[key] || ''));
    } else if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });
};

